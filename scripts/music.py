"""Generate a single music sample (to audition a style before the full build).
usage: XI_KEY=... python music.py <out.mp3> <seconds> "<prompt>"
The full per-section soundtrack is generated by build.py (gen_music) from section lengths.
ElevenLabs: max 2 concurrent requests on small plans; tracks can come back a few seconds short - build.py time-stretches."""
import sys, os, json, urllib.request
out, sec, prompt = sys.argv[1], float(sys.argv[2]), sys.argv[3]
body = json.dumps({'prompt': prompt, 'music_length_ms': int(sec * 1000), 'force_instrumental': True}).encode()
req = urllib.request.Request('https://api.elevenlabs.io/v1/music', body, {'xi-api-key': os.environ['XI_KEY'], 'Content-Type': 'application/json'})
open(out, 'wb').write(urllib.request.urlopen(req, timeout=600).read()); print('wrote', out)
